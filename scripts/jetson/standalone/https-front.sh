#!/usr/bin/env bash
# ViVeSec AI Box - standalone mode (E27 S2): the HTTPS front.
#
# An nginx container on the host network terminates TLS with the certificate
# from tls-pki.sh and relays to the web UI on loopback. It is the only network
# surface of a standalone box:
#   :443  the web UI (TLS 1.2/1.3, HSTS, security headers)
#   :80   a redirect to HTTPS and the CA certificate download (/aibox-ca.cer)
# A request for any other host name (or IP) is dropped without an answer, which
# also stops DNS rebinding. Client-sent VVS-* headers are removed: the identity
# headers are set by the box itself, never by a browser.
#
#   bash https-front.sh render [FILE]  # print (or write) the nginx configuration
#   bash https-front.sh deploy         # check, validate, (re)start, verify; rolls back on failure
#   bash https-front.sh verify         # checks from the box's point of view
#
# Parameters (environment), besides the AIBOX_TLS_* names of tls-pki.sh:
#   AIBOX_HTTPS_LISTEN     IPv4 addresses nginx binds   (default 0.0.0.0 = every
#                          interface, so an address change needs no new
#                          configuration; unknown names are dropped anyway)
#   AIBOX_HTTPS_UPSTREAM   the web UI, loopback only    (default 127.0.0.1:8080)
#   AIBOX_HTTPS_IMAGE      nginx image                  (default nginx:1.28-alpine)
#   AIBOX_HTTPS_CONF_DIR   rendered configuration       (default /data/https)
#   AIBOX_INTERNAL_PORTS   ports that must listen on loopback only
#                          (default "8080 8088 8090 11434": UI, adapter, RAG, Ollama)
set -euo pipefail

# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

CONTAINER=vivesec-https
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
tls_dir="${AIBOX_TLS_DIR:-/data/tls}"
conf_dir="${AIBOX_HTTPS_CONF_DIR:-/data/https}"
image="${AIBOX_HTTPS_IMAGE:-nginx:1.28-alpine}"
upstream="${AIBOX_HTTPS_UPSTREAM:-127.0.0.1:8080}"
internal_ports="${AIBOX_INTERNAL_PORTS:-8080 8088 8090 11434}"
# Identity headers only the box may set (adapter scope.py / identity.py).
CLIENT_HEADERS_DROPPED=(VVS-Drive VVS-User VVS-Session VVS-Identity VVS-Other-Drives)

log() { printf '[https-front] %s\n' "$*"; }

read_front_config() {
  local item
  read_box_names
  listen_ips=()
  while IFS= read -r item; do
    valid_ipv4 "$item" || die "invalid IPv4 address in AIBOX_HTTPS_LISTEN: $item"
    listen_ips+=("$item")
  done < <(split_list "${AIBOX_HTTPS_LISTEN:-0.0.0.0}")
  ((${#listen_ips[@]})) || die "AIBOX_HTTPS_LISTEN is empty"
  # The UI behind the front speaks plain HTTP, so it must never be reachable
  # from the network; only a loopback upstream is accepted.
  [[ $upstream =~ ^(127\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}|localhost|\[::1\]):[0-9]{1,5}$ ]] ||
    die "AIBOX_HTTPS_UPSTREAM must be a loopback host:port, got: $upstream"
}

security_headers() {
  local indent=$1
  cat <<EOF
${indent}add_header Strict-Transport-Security "max-age=31536000" always;
${indent}add_header X-Content-Type-Options "nosniff" always;
${indent}add_header X-Frame-Options "DENY" always;
${indent}add_header Content-Security-Policy "frame-ancestors 'none'" always;
${indent}add_header Referrer-Policy "no-referrer" always;
${indent}add_header Permissions-Policy "camera=(), geolocation=(), payment=(), usb=(), microphone=(self)" always;
EOF
}

ca_download_location() {
  local indent=$1 with_security=$2
  echo "${indent}location = /aibox-ca.cer {"
  echo "${indent}    root /srv/aibox-public;"
  echo "${indent}    types { }"
  echo "${indent}    default_type application/pkix-cert;"
  # A location with its own add_header loses the server-level ones.
  if [[ $with_security == yes ]]; then security_headers "${indent}    "; fi
  echo "${indent}    add_header Content-Disposition 'attachment; filename=\"aibox-ca.cer\"' always;"
  echo "${indent}    add_header Cache-Control \"no-store\" always;"
  echo "${indent}}"
}

listen_lines() {
  local port=$1 suffix=$2 ip
  for ip in "${listen_ips[@]}"; do echo "        listen $ip:$port$suffix;"; done
}

render() {
  local names header
  read_front_config
  names="${dns_names[*]} ${ip_names[*]}"
  cat <<EOF
# Generated by scripts/jetson/standalone/https-front.sh - do not edit by hand.
user nginx;
worker_processes auto;
pid /tmp/nginx.pid;
error_log /dev/stderr warn;

events {
    worker_connections 1024;
}

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    server_tokens off;
    sendfile on;
    keepalive_timeout 65s;

    # The root file system is read-only; every temp path lives on the /tmp tmpfs.
    client_body_temp_path /tmp/nginx-client-body;
    proxy_temp_path /tmp/nginx-proxy;
    fastcgi_temp_path /tmp/nginx-fastcgi;
    uwsgi_temp_path /tmp/nginx-uwsgi;
    scgi_temp_path /tmp/nginx-scgi;

    # No query strings in the log: they can carry file names.
    log_format aibox '\$remote_addr [\$time_local] "\$request_method \$uri \$server_protocol" '
                     '\$status \$body_bytes_sent \$request_time';
    access_log /dev/stdout aibox;

    client_max_body_size 64m;
    client_header_timeout 15s;
    client_body_timeout 60s;

    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305;
    ssl_prefer_server_ciphers off;
    ssl_ecdh_curve X25519:prime256v1:secp384r1;
    ssl_session_cache shared:TLS:10m;
    ssl_session_timeout 1d;
    ssl_session_tickets off;

    # Any other Host: drop the connection without an answer (also stops DNS
    # rebinding). The TLS default presents the box certificate, because a
    # browser opening https://<address>/ sends no server name at all; the
    # request is then routed by its Host header like any other.
    server {
$(listen_lines 80 " default_server")
        return 444;
    }
    server {
$(listen_lines 443 " ssl default_server")
        ssl_certificate /etc/aibox-tls/server.crt;
        ssl_certificate_key /etc/aibox-tls/server.key;
        return 444;
    }

    server {
$(listen_lines 80 "")
        server_name $names;
$(ca_download_location "        " no)
        location / {
            return 301 https://\$host\$request_uri;
        }
    }

    server {
$(listen_lines 443 " ssl")
        http2 on;
        server_name $names;
        ssl_certificate /etc/aibox-tls/server.crt;
        ssl_certificate_key /etc/aibox-tls/server.key;
$(security_headers "        ")
$(ca_download_location "        " yes)
        location / {
            proxy_pass http://$upstream;
            proxy_http_version 1.1;
            proxy_set_header Connection "";
            proxy_set_header Host \$host;
            proxy_set_header X-Forwarded-Proto https;
            proxy_set_header X-Forwarded-Host \$host;
            proxy_set_header X-Forwarded-For \$remote_addr;
            proxy_set_header X-Real-IP \$remote_addr;
            proxy_set_header Forwarded "";
EOF
  for header in "${CLIENT_HEADERS_DROPPED[@]}"; do
    echo "            proxy_set_header $header \"\";"
  done
  cat <<EOF
            proxy_hide_header X-Powered-By;
            # Answers stream and long-poll; nothing may be held back or cut short.
            proxy_buffering off;
            proxy_read_timeout 900s;
            proxy_send_timeout 900s;
        }
    }
}
EOF
}

# "address:port" of every listening TCP socket.
listeners() { ss -Hltn | awk '{print $4}'; }

is_loopback_address() {
  local address=${1%\%*}
  address=${address#[}
  address=${address%]}
  [[ $address =~ ^127\. || $address == ::1 || $address =~ ^::ffff:127\. ]]
}

check_internal_ports() {
  local socket address port wanted problems=0
  while IFS= read -r socket; do
    port=${socket##*:}
    address=${socket%:*}
    for wanted in $internal_ports; do
      if [[ $port == "$wanted" ]] && ! is_loopback_address "$address"; then
        echo "FAIL internal port $port listens on $address, not on loopback only"
        problems=1
      fi
    done
  done < <(listeners)
  return $problems
}

check_front_ports_free() {
  local socket address port ip
  docker inspect "$CONTAINER" >/dev/null 2>&1 && return 0
  while IFS= read -r socket; do
    port=${socket##*:}
    address=${socket%:*}
    address=${address#[}
    address=${address%]}
    [[ $port == 80 || $port == 443 ]] || continue
    for ip in "${listen_ips[@]}"; do
      if [[ $address == "$ip" || $address == 0.0.0.0 || $address == "*" || $address == :: ||
            $ip == 0.0.0.0 ]]; then
        die "port $port is already taken ($socket); in vivesecbox mode the adapter owns :80/:443"
      fi
    done
  done < <(listeners)
}

set_run_args() {  # the docker run options shared by validation and the service
  run_args=(--network host --read-only
    --tmpfs /tmp:rw,mode=1777,size=64m --tmpfs /var/cache/nginx:rw,size=16m
    --cap-drop ALL --cap-add NET_BIND_SERVICE --cap-add SETUID --cap-add SETGID --cap-add CHOWN
    --security-opt no-new-privileges
    -v "$1:/etc/nginx/nginx.conf:ro"
    -v "$tls_dir/server:/etc/aibox-tls:ro"
    -v "$tls_dir/public:/srv/aibox-public:ro"
    --entrypoint nginx)
}

cmd_deploy() {
  local stamp new_conf conf prev=""
  read_front_config
  command -v docker >/dev/null || die "docker is required"
  log "certificates"
  bash "$script_dir/tls-pki.sh" check
  log "internal ports"
  check_internal_ports || die "an internal service is reachable from the network; bind it to 127.0.0.1 first"
  check_front_ports_free
  if ! docker image inspect "$image" >/dev/null 2>&1; then
    log "image $image not present, trying to pull it"
    docker pull "$image" ||
      die "image $image is missing; on an offline box load it first: docker load -i nginx-image.tar"
  fi
  mkdir -p "$conf_dir"
  chmod 0755 "$conf_dir"
  conf="$conf_dir/nginx.conf"
  new_conf="$conf_dir/nginx.conf.new"
  render >"$new_conf"
  chmod 0644 "$new_conf"
  log "validating the configuration"
  set_run_args "$new_conf"
  docker run --rm --network none "${run_args[@]:2}" "$image" -t -q ||
    die "nginx rejected the configuration (kept in $new_conf)"
  stamp=$(date -u +%Y%m%d-%H%M%S)
  if [[ -f $conf ]]; then cp -p "$conf" "$conf.prev"; fi
  mv -f "$new_conf" "$conf"
  if docker inspect "$CONTAINER" >/dev/null 2>&1; then
    prev="$CONTAINER-prev-$stamp"
    docker rename "$CONTAINER" "$prev"
    docker stop "$prev" >/dev/null
  fi
  set_run_args "$conf"
  if docker run -d --name "$CONTAINER" --restart unless-stopped \
       --log-opt max-size=10m --log-opt max-file=3 \
       "${run_args[@]}" "$image" -g 'daemon off;' >/dev/null &&
     sleep 2 && cmd_verify; then
    if [[ -n $prev ]]; then docker rm "$prev" >/dev/null; fi
    log "HTTPS front running: https://${dns_names[0]}/"
    return 0
  fi
  echo "deploy failed, rolling back" >&2
  docker logs --tail 20 "$CONTAINER" >&2 2>&1 || true
  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
  if [[ -f $conf.prev ]]; then mv -f "$conf.prev" "$conf"; fi
  if [[ -n $prev ]]; then
    docker rename "$prev" "$CONTAINER"
    docker start "$CONTAINER" >/dev/null
    echo "the previous front runs again" >&2
  fi
  exit 1
}

cmd_verify() {
  local problems=0 ip name code fp served probe
  local -a probes=()
  read_front_config
  run_check() {  # description, then the command; prints PASS/FAIL
    local what=$1
    shift
    if "$@"; then echo "PASS $what"; else echo "FAIL $what"; problems=1; fi
  }
  # On every interface: probe the addresses the clients use.
  for ip in "${listen_ips[@]}"; do
    if [[ $ip != 0.0.0.0 ]]; then probes+=("$ip")
    elif ((${#ip_names[@]})); then probes+=("${ip_names[@]}")
    else probes+=(127.0.0.1)
    fi
  done
  fp=$(openssl x509 -in "$tls_dir/ca/ca.crt" -outform DER | openssl dgst -sha256 -r | cut -d' ' -f1)
  for probe in "${probes[@]}"; do
    for name in "${dns_names[@]}" "${ip_names[@]}"; do
      code=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 15 --cacert "$tls_dir/ca/ca.crt" \
        --resolve "$name:443:$probe" "https://$name/" 2>/dev/null || true)
      run_check "https://$name/ via $probe trusted by the box CA ($code)" \
        test "${code:0:1}" = 2 -o "${code:0:1}" = 3
      code=$(curl -sS -o /dev/null -w '%{http_code} %{redirect_url}' --max-time 10 \
        -H "Host: $name" "http://$probe/some/path?x=1" 2>/dev/null || true)
      run_check "http://$name/ redirects to https ($code)" \
        test "$code" = "301 https://$name/some/path?x=1"
    done
    served=$(curl -sS --max-time 10 -H "Host: ${dns_names[0]}" "http://$probe/aibox-ca.cer" 2>/dev/null |
      openssl dgst -sha256 -r | cut -d' ' -f1)
    run_check "http://$probe/aibox-ca.cer is the box CA" test "$served" = "$fp"
    run_check "unknown Host header is dropped" \
      bash -c "! curl -s -o /dev/null --max-time 5 -H 'Host: evil.example' 'http://$probe/'"
    run_check "unknown TLS server name gets no answer" \
      bash -c "! curl -s -o /dev/null --max-time 5 -k --resolve 'evil.example:443:$probe' https://evil.example/"
    code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 --cacert "$tls_dir/ca/ca.crt" \
      --resolve "${dns_names[0]}:443:$probe" -H 'Host: evil.example' "https://${dns_names[0]}/" 2>/dev/null || true)
    run_check "a known server name with a foreign Host header is not served ($code)" \
      test "${code:0:1}" != 2 -a "${code:0:1}" != 3
    run_check "HSTS header on HTTPS" bash -c "curl -sS -o /dev/null -D - --max-time 15 \
      --cacert '$tls_dir/ca/ca.crt' --resolve '${dns_names[0]}:443:$probe' 'https://${dns_names[0]}/' |
      grep -qi '^strict-transport-security: max-age='"
  done
  if command -v ss >/dev/null; then
    run_check "internal ports listen on loopback only ($internal_ports)" check_internal_ports
  fi
  return $problems
}

case ${1:-} in
  render)
    if [[ -n ${2:-} ]]; then render >"$2"; else render; fi ;;
  deploy) cmd_deploy ;;
  verify) cmd_verify ;;
  docker-args)  # internal: the hardened run options for CONF, one per line (tests)
    set_run_args "${2:?docker-args needs the nginx.conf path}"
    printf '%s\n' "${run_args[@]}" ;;
  *) sed -n '2,26p' "$0"; exit 2 ;;
esac
